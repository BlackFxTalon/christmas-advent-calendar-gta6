// The archive needs evidence as separate records. Materials stay the single
// source of truth: each "УЛИКА X · TITLE" block becomes one evidence item.
function deriveEvidence(materials) {
  return String(materials ?? "")
    .split(/\n{2,}(?=УЛИКА\s)/u)
    .map((block, index) => {
      const [header, ...rest] = block.split("\n");
      const match = header.match(/^УЛИКА\s+([A-ZА-Я])\s*·\s*(.+)$/u);
      return {
        id: match ? match[1].toLocaleLowerCase("ru-RU") : `e${index + 1}`,
        title: match ? match[2].trim() : header.trim(),
        text: rest.join("\n").trim(),
      };
    })
    .filter((evidence) => evidence.title);
}

for (const item of CASES) {
  item.evidence = deriveEvidence(item.materials).map((evidence) => ({ ...evidence, card: item.card }));
  if (!item.summary) {
    const firstParagraph = item.correct.split("\n\n")[0].trim();
    item.summary = firstParagraph.length > 240 ? `${firstParagraph.slice(0, 237)}…` : firstParagraph;
  }
}

export function getCaseById(id) {
  return CASES.find((item) => item.id === Number(id)) ?? null;
}
