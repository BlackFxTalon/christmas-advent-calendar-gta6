// Разбор времени: принимаем «23:46», «23.46», «23 46» и «23:46:00»; отклоняем 24:00, 23:60, «2346».
export function parseClockTime(text) {
  const m = String(text ?? "").normalize("NFKC").trim().match(/^(\d{1,2})[:.\s](\d{2})(?:[:.](00))?$/u);
  if (!m) return null;
  const h = Number(m[1]);
  const min = Number(m[2]);
  if (h > 23 || min > 59) return null;
  return `${String(h).padStart(2, "0")}:${m[2]}`;
}

// Возвращает исход, а не boolean: движку нужно знать, засчитывать ли попытку и какой текст отправить.
export function checkTimeAnswer(item, text) {
  const value = parseClockTime(text);
  if (value === null) return { outcome: "format", countsAsAttempt: false, reply: item.formatError };
  if (item.answers.some((a) => parseClockTime(a) === value)) {
    return { outcome: "correct", countsAsAttempt: true, reply: item.correct };
  }
  const trap = item.traps?.find((t) => parseClockTime(t.answer) === value);
  return { outcome: trap ? "trap" : "wrong", countsAsAttempt: true, reply: trap?.reply ?? item.incorrect };
}
